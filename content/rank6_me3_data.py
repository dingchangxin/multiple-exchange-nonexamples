extra = {}
for row in csv.DictReader(io.StringIO(AUXILIARY_CSV.strip())):
    H = tuple(int(ch) for ch in row["H"]) if row["H"] else tuple()
    key = (int(row["a"]), int(row["c"]), H)
    if key in extra:
        raise ValueError(f"Duplicate auxiliary coordinate: {key}")
    extra[key] = Fraction(row["value"])

def key_for_S(S):
    S = F(S)
    if S == A | B:
        return ("zero",)
    if A <= S and len(S & G) == 3 and len(S & B) == 0:
        return ("x", tuple(sorted(S & G)))
    if B <= S and len(S & G) == 3 and len(S & A) == 0:
        return ("y", tuple(sorted(S & G)))
    return ("v", len(S & A), len(S & B), tuple(sorted(S & G)))

def p_value(S):
    S = tuple(S)
    if len(S) != r or len(set(S)) != r or not set(S) <= ground:
        raise ValueError("p is defined on 6-subsets of {1,...,12}.")
    S = F(S)
    key = key_for_S(S)
    if key == ("zero",): return Fraction(0)
    if key[0] == "x": return x_value(key[1])
    if key[0] == "y": return y_value(key[1])
    _, a, c, H = key
    return extra[(a, c, H)]

# Populate all Plücker coordinates directly as Fractions
all_six = [F(S) for S in combinations(E, 6)]
p = {S: p_value(S) for S in all_six}


