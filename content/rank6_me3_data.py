def x_value(I):
    I = F(I)
    if I == F((1,2,3)):
        return Fraction(1)
    if I in x_half:
        return Fraction(1, 2)
    if I in x_quarter:
        return Fraction(1, 4)
    if I in x_eps:
        return eps
    raise KeyError(f"unknown x-coordinate {sorted(I)}")

def y_value(I):
    I = F(I)
    if len(I) != 3 or not I <= G:
        raise ValueError("Expected a 3-subset of G.")
    return Fraction(1) if I in y_one else eps

